"""Assemble docs/p7_results.md from the JSON results in bench/results/ (every number traces to a file).

    python -m bench.report
"""

import json
from pathlib import Path

from bench.env import header

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "bench" / "results"
OUT = ROOT / "docs" / "p7_results.md"


def load(name: str):
    p = RES / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def table(rows, headers) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def section_header(h: dict) -> str:
    d = h["device"]
    rows = [["Device", f"{d['cpu']} ({d['machine']}), {d['logical_cpus']} logical CPUs, {d['ram_gb']} GB - {d['note']}"],
            ["OS / Python / DuckDB", f"{d['os']} / {h['python']} / {h['duckdb']}"],
            ["llama.cpp", f"{h['llama_cpp']['build']} ({(h['llama_cpp']['version'] or ['?'])[0]})"],
            ["Models (sha256 prefix)", "; ".join(f"{k}: {v}" for k, v in h["models"].items())],
            ["Limits", f"SLM {h['threads']} threads; DuckDB {h['duckdb_limits']}"],
            ["VSS", h["vss_release"]],
            ["Seeds", f"history {h['seeds']['history']}; episodes {h['seeds']['episodes']}"],
            ["Splits", ", ".join(f"{k}: {len(v)}" for k, v in h["seeds"]["splits"].items())]]
    return table(rows, ["Item", "Value"])


def main():
    h = header()
    md = ["# P7 results - experiments and benchmarks", "",
          f"Generated by `python -m bench.report` on {h['generated_utc']}. Raw data: `bench/results/*.json`.", "",
          "> **All timings and memory figures are from an x86-64 laptop used as a proxy, not the 2-core ARM target.** "
          "All diagnostic results use **synthetic** scenarios; no real vehicle in the data has a labelled fault.", "",
          "## Run environment", "", section_header(h), ""]

    dx = load("diagnosis_eval.json")
    if dx:
        md += ["## Diagnosis accuracy (rules v1.1)", "",
               "Exact = the predicted set of causes equals the labelled set (S6 and S7 need both causes). "
               "`blind` = 16 episodes generated after the last rule change and never inspected before scoring.", "",
               table([[k, v["n"], v["exact"], v["top1"], v["top3"], v["abstained"], v["confidently_wrong"], v["S4_S5_no_fault"]]
                      for k, v in dx["summary"].items()],
                     ["Split", "Cases", "Exact", "Top-1", "Truth in top 3", "Abstained", "Confidently wrong", "S4/S5 no fault claimed"]), ""]

    b = load("experiment_b.json")
    if b:
        rows = []
        for v, by in b["summary"].items():
            t = by.get("test", {})
            hst = by.get("history", {})
            rows.append([v, f"{t.get('exact', '-')}/{t.get('n', '-')}", t.get("confidently_wrong", "-"),
                         t.get("false_fault_on_normal_or_bad_data", "-"), f"{hst.get('exact', '-')}/{hst.get('n', '-')}"])
        md += ["## Experiment B - diagnostic ablation", "",
               "Each component removed in turn (rules v1.1). `slm_*`: the SLM itself chooses the "
               "explanation (grammar-constrained to valid names), from raw window summaries or from the Δ-Signature.", "",
               table(rows, ["Variant", "Exact (test)", "Confidently wrong (test)", "False fault on S0/S4/S5 (test)", "Exact (history)"]), "",
               "- **The evidence gate matters most:** without data-quality checks, exact matches on the test split fall to a third.",
               "- **Baselines matter:** without them, more cases abstain.",
               "- **The physical model matters only when baselines are unrepresentative** (history: heatwave and degraded baselines).",
               "- **The SLMs cannot do the diagnosis:** both collapse to a fixed answer (mostly `none`, the first option listed), "
               "giving 10-15/17 confidently wrong. This was zero-shot without examples, the weakest fair test, but it supports "
               "keeping analytics deterministic.", ""]

    e0, e1 = load("experiment_e_v1_0.json"), load("experiment_e.json")
    if e0 and e1:
        rows = []
        for k in e1["corruptions"]:
            a, c = e0["corruptions"].get(k, {}), e1["corruptions"][k]
            bl = e1.get("blind_only", {}).get(k, {})
            rows.append([k, f"{a.get('confidently_wrong', '-')}/{a.get('n', '-')}", f"{c['confidently_wrong']}/{c['n']}",
                         f"{c['detected_by_gate']}/{c['n']}", f"{bl.get('exact', '-')}/{bl.get('n', '-')}", bl.get("confidently_wrong", "-")])
        md += ["## Experiment E - evidence quality and abstention", "",
               "Each case's target window is corrupted and diagnosed again. v1.0 = rules before P7 (dev + test cases). "
               "v1.1 = after three fixes the v1.0 run motivated (dev + test + blind; dev/test are no longer blind for v1.1). "
               "Correct = the original causes, plus the injected fault where the corruption creates one; reporting only a "
               "data problem counts as abstaining.", "",
               table(rows, ["Corruption", "Confidently wrong v1.0", "Confidently wrong v1.1", "Detected by gate v1.1",
                            "Exact, blind only", "Confidently wrong, blind only"]), "",
               "**v1.1 fixes:**",
               "- a Max < Avg contradiction must persist in at least 30% of samples (a single noisy sample was enough in v1.0);",
               "- load and cooling explain *abnormal* heating only;",
               "- a frozen or missing core temperature makes heating undecidable.", "",
               "**Not detected:** a 10-minute timestamp shift of the current signal. There is no alignment check yet; it caused "
               "no errors here.", "",
               "**Risk-coverage (v1.1)** - re-scoring all clean and corrupted cases with different acceptance thresholds:", "",
               table([[r["threshold"], r["coverage"], r["risk_wrong"], r["risk_confidently_wrong"]] for r in e1["risk_coverage"]],
                     ["Accept threshold", "Coverage", "Risk (any error)", "Risk (confidently wrong)"]), "",
               "The shipped threshold (2.5) keeps about 76% coverage with about 1% confidently wrong. Raising it to 3.0 removes "
               "almost all confidently wrong answers at about the same coverage.", ""]

    c = load("query_latency.json")
    if c:
        rows = []
        for src, v in c["sources"].items():
            for cls, s in v["classes"].items():
                rows.append([src, cls, s["n"], s["answered"], s["p50_ms"], s["p95_ms"], s["max_ms"]])
        md += ["## Experiment C - end-to-end query latency (in-process, warm)", "",
               table(rows, ["Vehicle", "Class", "Runs", "Answered", "p50 ms", "p95 ms", "max ms"]), "",
               f"Cold first question: " + ", ".join(f"{k} {v['cold_first_question_ms']} ms" for k, v in c["sources"].items()) + ".", ""]

    d = load("experiment_d.json")
    if d:
        rows = [[k, v["days_with_data"], v["raw_mb"], v["derived_mb"], v["mb_per_day"], v["six_weeks_mb"]]
                for k, v in d["storage"].items() if k in ("hist6w_s42", "ved_455", "ved_10", "zenodo_can_vehicle")]
        md += ["## Experiment D - resources", "", "**Storage** (Parquet, zstd):", "",
               table(rows, ["Source", "Days with data", "Raw MB", "Derived MB", "MB per day", "6 weeks, MB"]), "",
               "**Load phases** (all questions x 3 vehicles x 3 roles over HTTP):", ""]
        rows = []
        for ph, v in d["phases"].items():
            lat = v["latency"]
            rows.append([ph, lat["common"]["p95_ms"], lat["diagnostic"]["p95_ms"],
                         "; ".join(f"{k} {m} MB" for k, m in v["peak_mb"].items()), v.get("peak_total_mb", "-")])
        md += [table(rows, ["Phase", "Common p95 ms", "Diagnostic p95 ms", "Peak memory per process", "Peak total MB"]), "",
               "Memory is the resident set (Windows working set) of each process including its children (on Windows the venv "
               "`python.exe` is a launcher with the interpreter as a child), sampled every 100 ms. The 2 GB budget also has to hold the OS "
               "and the ingest process; this still needs measuring on the target under one cgroup limit.", ""]

    for name, title in (("experiment_f.json", "dev records + history (dry run, P5)"),
                        ("experiment_f_test.json", "17 held-out test records")):
        f = load(name)
        if not f:
            continue
        rows = []
        for model, v in f["models"].items():
            for cond, s in v["summary"].items():
                rows.append([model.split("-Instruct")[0].split("-instruct")[0], cond, f"{s['answers_with_untraceable_numbers']}/{s['n']}",
                             f"{s['answers_with_out_of_record_hypotheses']}/{s['n']}", f"{s['answers_with_overclaim']}/{s['n']}",
                             f"{s['covers_all_conclusions']}/{s['n']}", s["p50_wall_ms"]])
        md += [f"## Experiment F - ECD, {title}", "",
               "F1 free text · F2 static grammar · F3 ECD (service) · F4 ECD (driver).", "",
               table(rows, ["Model", "Cond.", "Untraceable numbers", "Hypotheses not in record", "Overclaims",
                            "Covers conclusions", "p50 ms"]), ""]

    md += ["## What P7 does not cover yet", "",
           "- **ARM target:** every latency and memory figure here must be re-measured on a 2-core ARM board (Graviton "
           "`t4g.small` or a Pi pinned to 2 cores) under one 2 GB limit.",
           "- **Real faults:** none of the recorded vehicles has a labelled thermal fault, so real-world diagnostic accuracy "
           "is unknown.",
           "- **Independent questions:** the routing test set was written by the same author as the rules.",
           "- **Experiment A** (input representation ablation) was not run; Experiment B's SLM variants cover the most "
           "important part (raw vs Δ-Signature input).", ""]
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
