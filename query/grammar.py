"""Generate the Tier 1 plan grammars from query/vocabulary.py.

    python -m query.grammar     # rewrites query/plan_grammar.gbnf and query/plan_grammar_compact.gbnf
"""

from pathlib import Path

from query.vocabulary import KEYS, VALUES

HERE = Path(__file__).parent
RULE = {"intent": "intent", "signal": "signal", "period": "period", "group_by": "groupby", "event_type": "eventtype"}
HEADER = ("# GENERATED by `python -m query.grammar` from query/vocabulary.py - do not edit by hand.\n"
          "# Closed vocabulary: the model can only emit enum values; no SQL, no commands, no free text.\n"
          "# A grammar-valid plan can still have the wrong intent: plans are validated again before execution.\n"
          "# (llama.cpp GBNF does not allow a rule to continue on a line that starts with \"|\".)\n\n")


def _alternatives(values: list[str], quoted: bool) -> str:
    q = '\\"' if quoted else ""
    return " | ".join(f'"{q}{v}{q}"' for v in values)


def json_grammar() -> str:
    parts = [f'\\"{k}\\": " {RULE[k]}' for k in KEYS]
    root = 'root ::= "{' + parts[0] + "".join(f' ", {p}' for p in parts[1:]) + ' "}"'
    rules = "\n\n".join(f"{RULE[k]} ::= {_alternatives(VALUES[k], True)}" for k in KEYS)
    return HEADER + root + "\n\n" + rules + "\n"


def compact_grammar() -> str:
    root = "root ::= " + ' " " '.join(RULE[k] for k in KEYS)
    rules = "\n\n".join(f"{RULE[k]} ::= {_alternatives(VALUES[k], False)}" for k in KEYS)
    return HEADER + "# Compact form: the five values, space-separated; code adds the keys.\n\n" + root + "\n\n" + rules + "\n"


FILES = {"plan_grammar.gbnf": json_grammar, "plan_grammar_compact.gbnf": compact_grammar}


def main():
    for name, fn in FILES.items():
        (HERE / name).write_text(fn(), encoding="utf-8")
        print(f"wrote query/{name}")


if __name__ == "__main__":
    main()
